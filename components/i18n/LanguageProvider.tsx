const I18nContext = createContext<{
  language: Language;
  setLanguage: (language: Language) => void;
  t: (source: string) => string;
}>({
  language: "en",
  setLanguage: () => {},
  t: (source) => source,
});

function dynamicTranslate(source: string, language: Language) {
  if (language === "en") return source;

  const dictionary = translations[language] ?? {};
  const supplemental = supplementalTranslations[language] ?? {};
  if (dictionary[source]) return dictionary[source];
  if (supplemental[source]) return supplemental[source];

  let match = source.match(/^Buy ([\d,.]+) RCX$/);
  if (match) {
    return `${dictionary["Buy"] ?? "Buy"} ${match[1]} RCX`;
  }

  match = source.match(/^Purchase limits: (.+)$/);
  if (match) {
    const labels: Record<Language, string> = {
      en: "Purchase limits",
      uk: "Ліміти покупки",
      de: "Kauflimits",
      fr: "Limites d'achat",
      es: "Límites de compra",
      it: "Limiti di acquisto",
      pl: "Limity zakupu",
      pt: "Limites de compra",
      nl: "Aankooplimieten",
      cs: "Limity nákupu",
    };
    return `${labels[language]}: ${match[1]}`;
  }

  return source;
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("en");

  useEffect(() => {
    const supported = new Set(languages.map((item) => item.code));
    const saved = localStorage.getItem("raccoonx-language") as Language | null;

    if (saved && supported.has(saved)) {
      setLanguageState(saved);
      return;
    }

    const browserLanguage =
      navigator.language.toLowerCase().split("-")[0] as Language;

    if (supported.has(browserLanguage)) {
      setLanguageState(browserLanguage);
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const setLanguage = useCallback((next: Language) => {
    setLanguageState(next);
    localStorage.setItem("raccoonx-language", next);
  }, []);

  const t = useCallback(
    (source: string) => dynamicTranslate(source, language),
    [language]
  );

  const value = useMemo(
    () => ({ language, setLanguage, t }),
    [language, setLanguage, t]
  );

  return (
    <I18nContext.Provider value={value}>
      {children}
    </I18nContext.Provider>
  );
}

export function useLanguage() {
  return useContext(I18nContext);
}

export function T({ children }: { children: string }) {
  const { t } = useLanguage();
  return <>{t(children)}</>;
}
